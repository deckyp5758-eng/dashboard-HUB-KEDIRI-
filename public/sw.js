const CACHE_NAME = 'hub-kediri-cache-v1';
const ASSETS_TO_CACHE = [
  '/',
  '/index.html',
  '/manifest.json',
  '/icon-192.svg',
  '/icon-512.svg'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(ASSETS_TO_CACHE);
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
        })
      );
    })
  );
  self.clients.claim();
});

// Cache static shell assets only, always bypass cache for HTML and dynamic API requests
self.addEventListener('fetch', (event) => {
  // Let all navigations and API calls go straight to network
  if (event.request.mode === 'navigate' || event.request.url.includes('/api/')) {
    return;
  }
});
